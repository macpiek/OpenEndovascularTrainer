import fs from 'node:fs/promises';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url);
const g=n=>`(local.get $${n})`,set=(n,x)=>`(local.set $${n} ${x})`,i=x=>`(i32.const ${x})`,f=x=>`(f64.const ${x})`;
const op=(name,...xs)=>`(${name} ${xs.join(' ')})`;
const ia=(a,b)=>op('i32.add',a,b),im=(a,b)=>op('i32.mul',a,b);
const add=(a,b)=>op('f64.add',a,b),sub=(a,b)=>op('f64.sub',a,b),mul=(a,b)=>op('f64.mul',a,b),div=(a,b)=>op('f64.div',a,b);
const at=x=>typeof x==='number'?i(x):x;
const load=x=>op('f64.load',im(at(x),i(8))),store=(x,v)=>op('f64.store',im(at(x),i(8)),v);
const component=(start,index,axis)=>load(ia(i(start+axis),im(index,i(3))));
const choose=(condition,a,b)=>`(if (result f64) ${condition} (then ${a}) (else ${b}))`;
let serial=0;
const loop=(name,body)=>{const id=serial++;return `${set(name,i(0))}(block $end${id}(loop $loop${id}
 (br_if $end${id}(i32.ge_s ${g(name)} (i32.const 7)))${body}
 ${set(name,ia(g(name),i(1)))}(br $loop${id})))`;};
const de=(index,axis)=>choose(op('i32.and',op('i32.lt_s',index,i(6)),op('i32.eq',op('i32.rem_s',index,i(3)),i(axis))),
    choose(op('i32.lt_s',index,i(3)),f(-1),f(1)),f(0));
const sum=(...terms)=>terms.reduce(add);
const axes=['x','y','z'];
const prepare=loop('col',
    axes.map((a,k)=>set('d'+a,de(g('col'),k))).join('')+
    axes.map((a,k)=>{
        const value=sum(...axes.map((_,j)=>mul(load(13+3*k+j),component(22,g('col'),j))));
        return store(ia(i(64+k),im(g('col'),i(3))),value);
    }).join('')+
    `(if ${g('geometric')} (then
      ${set('dl',sum(...axes.map((a,k)=>mul(load(1+k),g('d'+a)))))}
      ${store(ia(i(148),g('col')),div(op('f64.neg',g('dl')),mul(load(0),load(0))))}
      ${axes.map((a,k)=>{
        const b=(k+1)%3,c=(k+2)%3;
        return store(ia(i(106+k),im(g('col'),i(3))),div(sub(g('d'+a),mul(load(1+k),g('dl'))),load(0)))+
            store(ia(i(127+k),im(g('col'),i(3))),sub(mul(load(1+b),g('d'+axes[c])),mul(load(1+c),g('d'+axes[b]))))+
            store(ia(i(85+k),im(g('col'),i(3))),sub(mul(component(43,g('col'),b),load(4+c)),mul(component(43,g('col'),c),load(4+b))));
      }).join('')}
    ))`);
const entry=loop('row',
    axes.map((a,k)=>set('r'+a,de(g('row'),k))).join('')+
    set('spin',choose(op('i32.eq',g('row'),i(6)),f(1),f(0)))+
    loop('col',
        set('value',sum(...axes.map((_,k)=>mul(component(22,g('row'),k),component(64,g('col'),k)))))+
        `(if ${g('geometric')} (then
          ${axes.map((a,k)=>{
              const b=(k+1)%3,c=(k+2)%3;
              return set('u'+a,sum(div(sub(mul(component(106,g('col'),b),g('r'+axes[c])),mul(component(106,g('col'),c),g('r'+axes[b]))),load(0)),
                  mul(component(127,g('row'),k),load(ia(i(148),g('col')))),mul(component(106,g('col'),k),g('spin'))));
          }).join('')}
          ${axes.map((a,k)=>{
              const b=(k+1)%3,c=(k+2)%3;
              return set('v'+a,sub(add(sub(mul(g('u'+axes[b]),load(4+c)),mul(g('u'+axes[c]),load(4+b))),
                  mul(component(43,g('row'),b),component(85,g('col'),c))),mul(component(43,g('row'),c),component(85,g('col'),b))));
          }).join('')}
          ${set('along',sum(...axes.map((a,k)=>mul(g('v'+a),load(7+k)))))}
          ${set('value',add(g('value'),sum(...axes.map((a,k)=>mul(load(10+k),sub(g('v'+a),mul(load(7+k),g('along'))))))))}
        ))`+
        store(ia(i(155),ia(im(g('row'),i(7)),g('col'))),g('value'))));
const wat=`(module(import "env" "memory" (memory 1))
 (func(export "evaluate") (param $geometric i32)
 (local $row i32)(local $col i32)
 ${['dx','dy','dz','rx','ry','rz','ux','uy','uz','vx','vy','vz','spin','dl','along','value'].map(n=>`(local $${n} f64)`).join(' ')}
 ${prepare}${entry}))`;
const wabt=await require(process.env.OET_WABT_PATH||'wabt')(),parsed=wabt.parseWat('sharedAxisFrictionKernel.wat',wat);
parsed.resolveNames();parsed.validate();const {buffer}=parsed.toBinary({canonicalize_lebs:true});parsed.destroy();
await fs.writeFile(new URL('../../src/physics/kirchhoffSharedAxisFrictionKernelBytes.js',import.meta.url),
    `// Generated by scripts/physics/build-shared-axis-friction-kernel.mjs. Do not edit.\nexport const sharedAxisFrictionKernelBytes=new Uint8Array([${Array.from(buffer)}]);\n`);
console.log(`Generated ${buffer.length} bytes`);
