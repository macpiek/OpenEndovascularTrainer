// Optional build dependency: wabt@1.0.37 (or OET_WABT_PATH). Runtime uses only
// embedded bytes. The WAT keeps separate f64 multiply/subtract operations.
import fs from 'node:fs/promises';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url),wabt=await require(process.env.OET_WABT_PATH||'wabt')();
const source=await fs.readFile(new URL('kirchhoffSharedAxisBasisKernel.wat',import.meta.url),'utf8');
const parsed=wabt.parseWat('kirchhoffSharedAxisBasisKernel.wat',source);
parsed.resolveNames();parsed.validate();
const {buffer}=parsed.toBinary({canonicalize_lebs:true});parsed.destroy();
await fs.writeFile(new URL('../../src/physics/kirchhoffSharedAxisBasisKernelBytes.js',import.meta.url),
    `// Generated by scripts/physics/build-shared-axis-basis-kernel.mjs. Do not edit.\nexport const sharedAxisBasisKernelBytes=new Uint8Array([${Array.from(buffer)}]);\n`);
console.log(`Generated ${buffer.length} bytes`);
