// Build-only dependency: wabt@1.0.37 or OET_WABT_PATH. The generated f64
// expressions retain every parenthesis and scatter order of the JS inertia.
import fs from 'node:fs/promises';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url);
const g=n=>`(local.get $${n})`,set=(n,x)=>`(local.set $${n} ${x})`,i=x=>`(i32.const ${x})`,f=x=>`(f64.const ${x})`;
const op=(name,...xs)=>`(${name} ${xs.join(' ')})`,ia=(a,b)=>op('i32.add',a,b),im=(a,b)=>op('i32.mul',a,b);
const add=(a,b)=>op('f64.add',a,b),sub=(a,b)=>op('f64.sub',a,b),mul=(a,b)=>op('f64.mul',a,b),div=(a,b)=>op('f64.div',a,b),neg=a=>op('f64.neg',a);
const eq=(a,b)=>op('i32.eq',a,b),lt=(a,b)=>op('i32.lt_s',a,b);
const choose=(condition,a,b)=>`(if (result f64) ${condition} (then ${a}) (else ${b}))`;
const load=(base,index)=>op('f64.load',ia(g(base),im(typeof index==='number'?i(index):index,i(8))));
const store=(base,index,x)=>op('f64.store',ia(g(base),im(typeof index==='number'?i(index):index,i(8))),x);
const r=k=>load('record',k),dot=(a,b)=>[0,1,2].map(k=>mul(a(k),b(k))).reduce(add);
const names=(prefix,n)=>Array.from({length:n},(_,k)=>prefix+k);
let serial=0;
const loop=(name,end,body)=>{const id=serial++;return `${set(name,i(0))}(block $end${id}(loop $loop${id}(br_if $end${id}(i32.ge_s ${g(name)} ${end}))${body}${set(name,ia(g(name),i(1)))}(br $loop${id})))`;};
const scatter=(row,value)=>{
    const rowDof=op('i32.load',ia(g('indices'),i(row*4)));
    return set('rowDof',rowDof)+set('entry',ia(op('i32.sub',ia(im(g('rowDof'),g('width')),g('columnDof')),g('rowDof')),g('half')))+
        store('hessian',g('entry'),add(load('hessian',g('entry')),value));
};
const cross=(offset,k)=>k===0?sub(mul(g('wy'),r(offset+2)),mul(g('wz'),r(offset+1))):k===1?
    sub(mul(g('wz'),r(offset)),mul(g('wx'),r(offset+2))):sub(mul(g('wx'),r(offset+1)),mul(g('wy'),r(offset)));
const sign=choose(lt(g('col'),i(3)),f(-1),choose(lt(g('col'),i(6)),f(1),f(0)));
const axisNames=['dx','dy','dz'];
const spatial=loop('col',i(7),
    set('columnDof',op('i32.load',ia(g('indices'),im(g('col'),i(4)))))+
    axisNames.map((name,k)=>set(name,choose(eq(op('i32.rem_s',g('col'),i(3)),i(k)),sign,f(0)))).join('\n')+
    set('a0',div(neg(dot(k=>r(7+k),k=>g(axisNames[k]))),r(16)))+
    set('a1',div(dot(k=>r(4+k),k=>g(axisNames[k])),r(16)))+
    set('a2',choose(eq(g('col'),i(6)),f(1),f(0)))+
    [0,1,2].map(k=>set('dTorque'+k,dot(j=>r(20+k*3+j),j=>g('a'+j)))).join('\n')+
    // THREE's vector rotation expression; no replacement rotation matrix.
    set('tx',mul(f(2),sub(mul(r(1),g('a2')),mul(r(2),g('a1')))))+
    set('ty',mul(f(2),sub(mul(r(2),g('a0')),mul(r(0),g('a2')))))+
    set('tz',mul(f(2),sub(mul(r(0),g('a1')),mul(r(1),g('a0')))))+
    set('wx',sub(add(add(g('a0'),mul(r(3),g('tx'))),mul(r(1),g('tz'))),mul(r(2),g('ty'))))+
    set('wy',sub(add(add(g('a1'),mul(r(3),g('ty'))),mul(r(2),g('tx'))),mul(r(0),g('tz'))))+
    set('wz',sub(add(add(g('a2'),mul(r(3),g('tz'))),mul(r(0),g('ty'))),mul(r(1),g('tx'))))+
    set('dl',dot(k=>r(13+k),k=>g(axisNames[k])))+
    [0,1,2].map(k=>set('df',sub(div(sub(add(sub(mul(cross(4,k),r(18)),mul(cross(7,k),r(17))),
        mul(r(4+k),g('dTorque1'))),mul(r(7+k),g('dTorque0'))),r(16)),div(mul(r(10+k),g('dl')),r(16))))+
        scatter(k,neg(g('df')))+scatter(3+k,g('df'))).join('\n')+
    scatter(6,g('dTorque2')));
// Reuse the material kernel's no-longer-live records after its scatter. This
// keeps the tangent in one fixed memory without copying a global matrix.
const wat=`(module(import "env" "memory" (memory 1))
 (func(export "assemble") ${['records','dofs','count','hessian','width','half'].map(n=>`(param $${n} i32)`).join(' ')}
 ${['edge','record','indices','col','columnDof','rowDof','entry'].map(n=>`(local $${n} i32)`).join(' ')}
 ${['dx','dy','dz','a0','a1','a2','tx','ty','tz','wx','wy','wz','dl','df',...names('dTorque',3)].map(n=>`(local $${n} f64)`).join(' ')}
 ${loop('edge',g('count'),set('record',ia(g('records'),im(g('edge'),i(91*8))))+set('indices',ia(g('dofs'),im(g('edge'),i(11*4))))+spatial)}))`;
const wabt=await require(process.env.OET_WABT_PATH||'wabt')(),parsed=wabt.parseWat('sharedAxisInertiaKernel.wat',wat);
parsed.resolveNames();parsed.validate();const {buffer}=parsed.toBinary({canonicalize_lebs:true});parsed.destroy();
await fs.writeFile(new URL('../../src/physics/kirchhoffSharedAxisInertiaKernelBytes.js',import.meta.url),
    `// Generated by scripts/physics/build-shared-axis-inertia-kernel.mjs. Do not edit.\nexport const sharedAxisInertiaKernelBytes=new Uint8Array([${Array.from(buffer)}]);\n`);
console.log(`Generated ${buffer.length} bytes`);
