// Optional build-time dependency: wabt@1.0.37 (not shipped to the browser).
import fs from 'node:fs/promises';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const wabt = await require(process.env.OET_WABT_PATH || 'wabt')();
const base = await fs.readFile(new URL('kirchhoffLinearKernel.wat', import.meta.url), 'utf8');
const assembly = await fs.readFile(new URL('kirchhoffBandLUAssembly.wat', import.meta.url), 'utf8');
const source = base.slice(0, base.lastIndexOf(')')) + assembly + '\n)';
const parsed = wabt.parseWat('kirchhoffLinearKernel.wat', source);
parsed.validate();
const { buffer } = parsed.toBinary({ canonicalize_lebs: true });
await fs.writeFile(new URL('../../src/physics/kirchhoffLinearKernelBytes.js', import.meta.url),
    `// Generated by scripts/physics/build-linear-kernel.mjs. Do not edit.\nexport const linearKernelBytes = new Uint8Array([${Array.from(buffer)}]);\n`);
parsed.destroy();
console.log(`Generated ${buffer.length} bytes`);
