// Optional SIMD companion for the ordinary band LU. Adjacent columns are
// independent during elimination and row swaps; every scalar lane retains
// the original f64 multiply/subtract and the same pivot/backsolve order.
import fs from 'node:fs/promises';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url);
const source=await fs.readFile(new URL('kirchhoffLinearKernel.wat',import.meta.url),'utf8');
const start=source.indexOf('  (func (export "solveGeneralBandLU")');
const end=source.indexOf('  ;; Opt-in incremental-contact prototype:',start);
if(start<0||end<=start)throw new Error('Ordinary band LU source not found');
let body=source.slice(start,end);
const once=(old,value)=>{
    if(body.split(old).length!==2)throw new Error('Expected one kernel insertion site: '+old);
    body=body.replace(old,value);
};
once('    (local $best f64)', '    (local $pair v128) (local $ratioPair v128)\n    (local $best f64)');
once('        (block $swapDone (loop $swap',`
        (block $swapPairDone (loop $swapPair
          (br_if $swapPairDone (i32.ge_s (local.get $j) (local.get $end)))
          (local.set $p (i32.add (local.get $kb) (i32.mul (local.get $j) (i32.const 8))))
          (local.set $q (i32.add (local.get $pb) (i32.mul (local.get $j) (i32.const 8))))
          (local.set $pair (v128.load (local.get $p)))
          (v128.store (local.get $p) (v128.load (local.get $q)))
          (v128.store (local.get $q) (local.get $pair))
          (local.set $j (i32.add (local.get $j) (i32.const 2))) (br $swapPair)))
        (block $swapDone (loop $swap`);
once('          (block $updateDone (loop $update',`
          (local.set $ratioPair (f64x2.splat (local.get $ratio)))
          (block $updatePairDone (loop $updatePair
            (br_if $updatePairDone (i32.ge_s (local.get $j) (local.get $ke)))
            (local.set $p (i32.add (local.get $ib) (i32.mul (local.get $j) (i32.const 8))))
            (v128.store (local.get $p) (f64x2.sub (v128.load (local.get $p))
              (f64x2.mul (local.get $ratioPair) (v128.load (i32.add (local.get $kb) (i32.mul (local.get $j) (i32.const 8)))))))
            (local.set $j (i32.add (local.get $j) (i32.const 2))) (br $updatePair)))
          (block $updateDone (loop $update`);
const wat=`(module (import "env" "memory" (memory 1))\n${body})`;
const wabt=await require(process.env.OET_WABT_PATH||'wabt')();
const parsed=wabt.parseWat('bandSimdKernel.wat',wat,{simd:true});
parsed.resolveNames();parsed.validate();
const {buffer}=parsed.toBinary({canonicalize_lebs:true});parsed.destroy();
await fs.writeFile(new URL('../../src/physics/kirchhoffBandSimdKernelBytes.js',import.meta.url),
    `// Generated by scripts/physics/build-band-simd-kernel.mjs. Do not edit.\nexport const bandSimdKernelBytes=new Uint8Array([${Array.from(buffer)}]);\n`);
console.log(`Generated ${buffer.length} bytes`);
